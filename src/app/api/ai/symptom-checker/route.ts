export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const symptomsText = (body.symptoms_text || '').trim();
    const selectedSymptoms: string[] = Array.isArray(body.selected_symptoms) ? body.selected_symptoms : [];
    const language = body.language === 'kz' ? 'kz' : 'ru';
    const isKz = language === 'kz';
    const targetCity = (body.city || 'Алматы').trim();

    const combinedText = `${symptomsText} ${selectedSymptoms.join(' ')}`.toLowerCase();

    // Match rule
    let matchedRule = SYMPTOM_RULES.find((rule) =>
      rule.keywords.some((kw) => combinedText.includes(kw.toLowerCase()))
    );

    if (!matchedRule) {
      // Fallback rule for general therapy
      matchedRule = {
        keywords: [],
        specialty: isKz ? 'Терапевт' : 'Терапевт (Врач общей практики)',
        doctorSpecialtyMatches: ['Терапевт', 'Врач УЗИ'],
        causes_ru: ['Общее переутомление или начальные проявления инфекции', 'Вегетативная дисфункция или астенический синдром', 'Снижение иммунного статуса'],
        causes_kz: ['Жалпы шаршау немесе вирустық белгілер', 'Астениялық синдром', 'Иммунитет әлсіреуі'],
        tests_ru: ['Общий анализ крови (ОАК) с лейкоформулой', 'Биохимический анализ крови', 'Первичная консультация врача-терапевта'],
        tests_kz: ['Жалпы қан талдауы (ОАК)', 'Қан биохимиясы', 'Терапевт дәрігерінің алғашқы қарауы'],
      };
    }

    const potentialConditions = isKz ? matchedRule.causes_kz : matchedRule.causes_ru;
    const recommendedExaminations = isKz ? matchedRule.tests_kz : matchedRule.tests_ru;
    const disclaimer = isKz
      ? '⚠️ Бұл ресми диагноз емес. Жағдай нашарласа немесе жедел симптомдар байқалса, шұғыл дәрігерге немесе 103 жедел жәрдеміне жүгініңіз.'
      : '⚠️ Не является официальным диагнозом. При ухудшении состояния или острых симптомах немедленно обратитесь к врачу или вызовите скорую помощь 103.';

    // Find recommended doctors
    const clinicsMap = new Map<string, any>(mockData.clinics.map((c: any) => [c.id, c]));

    const targetSpecs = matchedRule.doctorSpecialtyMatches.map((s) => s.toLowerCase());
    const matchedDoctors = mockData.doctors.filter((doc: any) => {
      const docSpec = (doc.specialty || '').toLowerCase();
      return targetSpecs.some((ts) => docSpec.includes(ts) || ts.includes(docSpec));
    });

    // Filter by city first
    const tCityLower = targetCity.toLowerCase();
    let cityDoctors = matchedDoctors.filter((doc: any) => {
      const clinic = clinicsMap.get(doc.clinic_id);
      if (!clinic) return false;
      const cCity = (clinic.city || '').toLowerCase();
      return cCity.includes(tCityLower) || tCityLower.includes(cCity);
    });

    // If fewer than 2 in selected city, supplement with top doctors from all cities
    if (cityDoctors.length < 3) {
      const existingIds = new Set(cityDoctors.map((d: any) => d.id));
      const otherDoctors = matchedDoctors
        .filter((d: any) => !existingIds.has(d.id))
        .sort((a: any, b: any) => (b.rating || 0) - (a.rating || 0));
      cityDoctors = [...cityDoctors, ...otherDoctors];
    }

    // Sort by rating desc
    cityDoctors.sort((a: any, b: any) => (b.rating || 0) - (a.rating || 0));

    const recommendedDoctors = cityDoctors.slice(0, 4).map((doc: any) => {
      const clinic = clinicsMap.get(doc.clinic_id);
      return {
        id: doc.id,
        name: `${doc.first_name} ${doc.last_name}`,
        specialty: doc.specialty,
        clinic_id: doc.clinic_id,
        clinic_name: clinic?.name || (isKz ? 'Медициналық орталық' : 'Медицинский центр'),
        price: doc.consultation_price || 12000,
        rating: doc.rating || 4.9,
        photo_url: doc.photo_url || null,
        city: clinic?.city || targetCity,
      };
    });

    const aiAnalysis = isKz
      ? `Сіздің белгілеріңіз бойынша бастапқы ұсыныс: **${matchedRule.specialty}** қарауы қажет.\n\n` +
        `🔍 **Болжамды жағдайлар:** ${potentialConditions.join(', ')}\n` +
        `🧪 **Ұсынылатын талдаулар:** ${recommendedExaminations.join(', ')}\n\n` +
        `${disclaimer}`
      : `На основе указанных симптомов рекомендуется консультация специалиста: **${matchedRule.specialty}**.\n\n` +
        `🔍 **Возможные ориентиры:** ${potentialConditions.join(', ')}\n` +
        `🧪 **Рекомендуемые обследования:** ${recommendedExaminations.join(', ')}\n\n` +
        `${disclaimer}`;

    return NextResponse.json({
      potential_conditions: potentialConditions,
      specialty: matchedRule.specialty,
      recommended_examinations: recommendedExaminations,
      disclaimer,
      recommended_doctors: recommendedDoctors,
      ai_analysis: aiAnalysis,
    });
  } catch (err: any) {
    return NextResponse.json(
      { detail: err?.message || 'Symptom analysis failed' },
      { status: 400 }
    );
  }
}
